"""
Packet data model for AeroNetGuard.

This module defines the Packet data structure representing a complete logical
message generated by an airport department node for transmission across the network.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Any
import uuid


@dataclass
class Packet:
    """
    Logical network packet model.

    Represents an end-to-end communication message between a source airport node
    and a destination airport node.
    """

    source: str
    destination: str
    payload: str
    packet_id: str = field(default_factory=lambda: uuid.uuid4().hex)
    sequence_number: int = 0
    route: List[str] = field(default_factory=list)
    status: str = "created"

    def __post_init__(self) -> None:
        """Validate packet fields upon instantiation."""
        self.validate()

    def validate(self) -> None:
        """
        Validate packet attributes.

        :raises ValueError: If source, destination, or status are empty, or sequence_number is negative.
        :raises TypeError: If payload is not a string, or sequence_number is not an integer.
        """
        if not isinstance(self.source, str) or not self.source.strip():
            raise ValueError("Packet source cannot be empty.")
        if not isinstance(self.destination, str) or not self.destination.strip():
            raise ValueError("Packet destination cannot be empty.")
        if not isinstance(self.payload, str):
            raise TypeError("Packet payload must be a string.")
        if type(self.sequence_number) is not int:
            raise TypeError("Packet sequence_number must be an integer.")
        if self.sequence_number < 0:
            raise ValueError("Packet sequence_number cannot be negative.")
        if not isinstance(self.status, str) or not self.status.strip():
            raise ValueError("Packet status cannot be empty.")
        if not isinstance(self.route, list):
            raise TypeError("Packet route must be a list of strings.")

    def set_route(self, route: List[str]) -> None:
        """
        Assign the calculated route to the packet.

        :param route: List of node names along the path.
        :raises TypeError: If route is not a list.
        """
        if not isinstance(route, list):
            raise TypeError("Route must be a list of node names.")
        self.route = list(route)

    def update_status(self, status: str) -> None:
        """
        Update the current status of the packet.

        :param status: New status string (e.g. 'framed', 'transmitting', 'delivered').
        :raises ValueError: If status is empty.
        """
        if not isinstance(status, str) or not status.strip():
            raise ValueError("Packet status cannot be empty.")
        self.status = status

    def to_dict(self) -> Dict[str, Any]:
        """
        Serialize packet attributes to a JSON-compatible dictionary.

        :return: Dict representation of the packet.
        """
        return {
            "packet_id": self.packet_id,
            "source": self.source,
            "destination": self.destination,
            "payload": self.payload,
            "sequence_number": self.sequence_number,
            "route": list(self.route),
            "status": self.status,
        }

    def __repr__(self) -> str:
        return (
            f"<Packet id={self.packet_id[:8]} src={self.source} "
            f"dst={self.destination} seq={self.sequence_number} status={self.status}>"
        )
